/** Removes zero or more items from an array by index.
 * Mutates the original array.
 *
 * @template T
 * @param {T[]} array
 * @param  {...number} indexes
 * @returns {T[]} A new array containing the removed items in reverse index order.
 */
export function removeMultipleIndexes(array, ...indexes) {
  let ret = [];

  indexes.sort(sort.numeric.descending);

  for (const index of indexes) ret.push(array.splice(index, 1)[0]);

  return ret;
}

/** Returns a new array containing the non-null elements
 * of the target array, even if it is sparse.
 *
 * @param {Array} array
 * @returns {Array}
 */
export function compactSparseArray(array) {
  return array.filter(function (x) {
    return x != null;
  });
}

/**
 * @template T
 * @param {T[][]} array Arrays nested in arrays arbitrarily-many layers deep. Does not mutate.
 * @param {T[]} [destinationArray] Optional destination array. If provided, elements will be appended to this array.
 * @returns {T[]} An array with all non-Array children, whose elements are the array elements of the root array and subarrays, in depth-first-traversal order.
 */
export function flatten(array, destinationArray = []) {
  const length = array.length;

  for (let i = 0; i < length; i++) {
    const value = array[i];

    if (Array.isArray(value)) {
      flatten(value, destinationArray);
    } else {
      destinationArray.push(value);
    }
  }

  return destinationArray;
}

/**
 * @param {number[]} array
 * @returns {number} The total of the numeric array, ignoring any non-numbers. Zero if no numbers are present.
 */
export function sum(array) {
  let total = 0;

  for (let i = 0; i < array?.length; i++) {
    if (isNumber(array[i])) total += array[i];
  }

  return total;
}

/**
 * @param {number[]} array
 * @returns {number} The product of the numeric array, ignoring any non-numbers. One if no numbers are present.
 */
export function product(array) {
  let product = 1;

  for (let i = 0; i < array?.length; i++) {
    if (isNumber(array[i])) product *= array[i];
  }

  return product;
}

/**
 * @param {number[]} array
 * @returns {number} The arithmetic mean (average) of the numeric array, ignoring any non-numbers.
 */
export function mean(array) {
  return sum(array) / array?.length;
}

/**
 * @param {number[]} array
 * @returns {{ max: number, index: number }?}
 */
export function findMax(array) {
  if (!array.length) return null;

  let max = array[0];
  let index = 0;

  for (let i = 1; i < array.length; i++) {
    if (array[i] > max) {
      max = array[i];
      index = i;
    }
  }

  return { max, index };
}

/**
 * @param {number[]} array1
 * @param {number[]} array2
 * @returns {number[]} A new array containing the memberwise difference of the numeric arrays.
 */
export function memberwiseSubtract(array1, array2) {
  const ret = [];

  for (let i = 0; i < array1.length; i++) {
    ret[i] = array1[i] - array2[i];
  }

  return ret;
}

