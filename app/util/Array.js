/**
 * @param {number} sizeOrMin The size of the range, or the minimum value of the range if a max was also provided.
 * @param {number} [max] The maximum value of the range.
 * @returns {number[]} A numeric array containing [0, 1, ..., size - 1], or [min, min + 1, ..., max] if a max was provided.
 */
export function range(sizeOrMin, max) {
  let size, start;
  if (max != null) {
    size = max - sizeOrMin + 1;
    start = sizeOrMin;
  } else {
    max = size = sizeOrMin;
    start = 0;
  }

  const ret = array(size);
  for (let i = 0; i < size; i++) ret[i] = i + start;
  return ret;
}

/**
 * @template T
 * @param {T[]} arr
 * @returns {T[]}
 */
export function cloneRectangularArray(arr) {
  const width = arr.length;
  if (width === 0) return [];
  const height = arr[0].length;

  const ret = array(width, height);

  for (let i = 0; i < width; i++) {
    for (let j = 0; j < height; j++) {
      ret[i][j] = arr[i][j];
    }
  }

  return ret;
}

/**
 * @template T
 * @param {T[]} array
 * @param {() => number} randomFunc
 * @returns {T[]} A new array containing the elements of the input array in randomized order.
 */
export function arrShuffle(array, randomFunc = Math.random) {
  return arrShuffleInPlace([...array], randomFunc);
}

/**
 * As I later discovered, this is apparently called the Fisher-Yates shuffle, here invented independently.
 *
 * @template T
 * @param {T[]} array
 * @param {() => number} randomFunc
 * @returns {T[]} The original input array, mutated, in randomized order.
 */
export function arrShuffleInPlace(array, randomFunc = Math.random) {
  for (let i = 0; i < array.length - 1; i++) {
    const swap = randInt(i, array.length - 1, randomFunc);
    if (i !== swap) arrSwap(array, i, swap);
  }

  return array;
}

/** Mutates the input array to swap two items in-place.
 * @param {*[]} array
 * @param {number} i1
 * @param {number} i2
 */
function arrSwap(array, i1, i2) {
  // Tested, found to be performant in the abstract, in bulk.
  // See https://github.com/espoire/performance
  array[i1] = array.splice(i2, 1, array[i1])[0];
}

/**
 * @template T
 * @param {T[]} arr A 2D rectangular array
 * @param {'sunwise' | 'widdershins' | 'turnabout'} direction
 * @returns {T[]} A new 2D rectangular array containing the elements of arr, rotated as indicated.
 */
export function rotateRectangularArray(arr, direction = 'sunwise') {
  const width = arr.length;
  const height = arr[0].length;
  const ret = direction === 'turnabout' ? array(width, height) : array(height, width);

  for (let x = 0; x < width; x++) {
    for (let y = 0; y < height; y++) {
      const { dx, dy } = _getRotatedCoordinates(direction, width, height, x, y);
      ret[dx][dy] = arr[x][y];
    }
  }

  return ret;
}

function _getRotatedCoordinates(direction, width, height, x, y) {
  switch (direction) {
    case 'sunwise':
      return {
        dx: y,
        dy: width - 1 - x,
      };

    case 'widdershins':
      return {
        dx: height - 1 - y,
        dy: x,
      };

    case 'turnabout':
      return {
        dx: width - 1 - x,
        dy: height - 1 - y,
      };

    default:
      throw new Error(
        `rotateRectangularArray() direction argument must be 'sunwise' | 'widdershins' | 'turnabout', given: ${valueAndType(direction)}`
      );
  }
}

/**
 * Recursively crawls the input multidimensional arrays and checks for memberwise equality (===) at each location.
 * No object support, no circular-linking support; subarrays are the only special case.
 *
 * @param {*[]} arr1
 * @param {*[]} arr2
 */
export function memberwiseEquals(arr1, arr2) {
  if (arr1.length !== arr2.length) return false;

  for (let i = 0; i < arr1.length; i++) {
    if (Array.isArray(arr1[i])) {
      if (!Array.isArray(arr2[i])) return false;
      if (!memberwiseEquals(arr1[i], arr2[i])) return false;
    } else if (Array.isArray(arr2[i])) {
      return false;
    } else {
      if (arr1[i] !== arr2[i]) return false;
    }
  }

  return true;
}

/**
 * Checks whether two arrays are "multiset equal", that is:
 * contain all the same elements, including the same number
 * of occurrences of each element, in any order.
 * 
 * Note that object elements are compared by reference, not
 * by value. This means that two different object instances
 * with identical properties will be treated as different.
 *
 * @template T
 * @param {T[]} arr1
 * @param {T[]} arr2
 * @returns {boolean} True if both inputs are arrays which are multiset equal, false otherwise.
 */
export function multisetEquals(arr1, arr2) {
  if (!Array.isArray(arr1) || !Array.isArray(arr2)) return false; // Non-array inputs always treated as not multiset equal
  if (arr1.length !== arr2.length) return false;

  const count = new Map();

  // Construct a map of value:count pairs
  for (const x of arr1) count.set(x, (count.get(x) ?? 0) + 1);

  for (const x of arr2) {
    // If `arr2` contains any elements not in `arr1`, return false
    if (!count.has(x)) return false;

    // Decrement the count for the element, remove key if depleted
    count.set(x, count.get(x) - 1);
    if (count.get(x) === 0) count.delete(x);
  }

  // Check if all keys were removed
  return count.size === 0;
}

/**
 * @template T
 * @param {T[]} arr 
 * @param {(value: T, index: number, array: T[]) => boolean} testFn
 * @returns {number} The number of elements satisfying the test function, or the number of elements present if no testFn is provided.
 */
export function countWhere(arr, testFn) {
  if (testFn == null) return arr.length;

  let total = 0;

  arr.forEach((member, index, array) => {
    if (testFn(member, index, array)) total++;
  });

  return total;
}

/**
 * @param {number[]} arr A sorted number array
 * @param {number} target The number to find
 * @returns {number} The largest array index holding a value at or below the target number, or -1 if no such index exists.
 */
export function findLargestArrayIndexAtOrBelowTarget(arr, target) {
  if (target < arr[0]) return -1;

  let min = 0,
    max = arr.length - 1,
    test,
    passed;

  while (min < max) {
    test = Math.ceil((min + max) / 2);
    passed = arr[test] <= target;
    if (passed) {
      min = test;
    } else {
      max = test - 1;
    }
  }

  return test - !passed;
}

/**
 * @template T
 * @param {T[]} arr
 * @param {null | (a: T, b: T) => boolean} predicate A function which returns true if two elements are considered duplicates. If absent, Set equality is used.
 * @returns {T[]} A new array containing the unique elements of the input array, as defined by the predicate.
 */
export function removeDuplicates(arr, predicate = null) {
  if (predicate == null) return Array.from(new Set(arr));
  const ret = [];

  for (const element of arr) {
    if (!ret.some(existing => predicate(existing, element))) {
      ret.push(element);
    }
  }

  return ret;
}

/**
 * @param {*[]} arr
 * @returns {boolean} True if the provided array contains any pair of duplicate members (as defined by Set equality), false otherwise
 */
export function hasDuplicates(arr) {
  return arr.length !== removeDuplicates(arr).length;
}

/**
 * "Fancy" in that it returns both the element in question and its index.
 * @template T
 * @param {T[]} arr
 * @param {(value: T, index: number, array: T[]) => boolean} predicate
 * @returns {{ element: T, index: number }?}
 */
export function fancyFindLast(arr, predicate) {
  for (let i = arr.length - 1; i >= 0; i--) {
    if (predicate(arr[i], i, arr)) return { element: arr[i], index: i };
  }
}

